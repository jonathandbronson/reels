"""Build index.html from assets/source/voice/timing.json.  Run: python3 build_index.py"""
import json
from pathlib import Path

HERE = Path(__file__).parent
t = json.loads((HERE / "assets/source/voice/timing.json").read_text())
TAIL = 0.9  # hold after the last line
slots = {}
for i, x in enumerate(t):
    end = t[i + 1]["start"] if i + 1 < len(t) else x["start"] + x["duration"] + TAIL
    slots[x["scene"]] = (round(x["start"], 3), round(end - x["start"], 3))
total = round(sum(slots[s][1] for s in slots), 3)
vo_len = round(t[-1]["start"] + t[-1]["duration"], 3)

# Shots: (id, src, scene, media_start, clip_seconds_used)
SHOTS = [
    ("shot-hook", "sail.mp4", "hook", 0.0, 1.0),
    ("shot-record", "sail.mp4", "record", 0.6, 1.4),
    ("shot-flood", "sink.mp4", "flood", 0.0, 0.9),
    ("shot-down", "sink.mp4", "down", 0.9, 0.65),
    ("shot-reef", "seafloor.mp4", "reef", 0.0, 1.66),
]

out = []
lane = 0
for sid, src, scene, ms, used in SHOTS:
    start, dur = slots[scene]
    rate = round(used / dur, 3)
    out.append(
        f'      <video id="{sid}" class="clip shot" src="assets/blender/{src}" muted data-start="{start}" '
        f'data-duration="{dur}" data-media-start="{ms}" data-playback-rate="{rate}" data-track-index="0"></video>'
    )
for scene, (start, dur) in slots.items():
    out.append(
        f'      <div id="{scene}" data-composition-id="{scene}" class="scene clip" '
        f'data-composition-src="compositions/{scene}.html" data-start="{start}" data-duration="{dur}" '
        f'data-track-index="1" data-track-kind="graphics" data-width="1080" data-height="1920"></div>'
    )
out.append(f'      <audio id="vo" class="clip" src="assets/source/voice/vo.wav" data-start="0" data-duration="{vo_len}" data-track-index="2"></audio>')
for i, (scene, (start, _)) in enumerate(list(slots.items())[1:], 1):
    out.append(f'      <audio id="sfx-whoosh{i}" class="clip" src="assets/source/sounds/whoosh.wav" data-start="{round(start - 0.48, 3)}" data-duration="0.6" data-volume="0.45" data-track-index="3"></audio>')
    out.append(f'      <audio id="sfx-hit{i}" class="clip" src="assets/source/sounds/hit.wav" data-start="{start}" data-duration="0.5" data-volume="1.3" data-track-index="4"></audio>')

html = f"""<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="assets/vendor/gsap.min.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: #1d3fd8; }}
      #root {{ position: relative; width: 100%; height: 100%; font-family: "Inter", sans-serif; }}
      .shot {{ position: absolute; left: 150px; top: 620px; width: 780px; height: 600px; object-fit: cover; border-radius: 36px; }}
      .scene {{ position: absolute; inset: 0; }}
    </style>
  </head>
  <body>
    <!-- Generated by build_index.py from assets/source/voice/timing.json. Edit that script, not this file. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-width="1080" data-height="1920">
{chr(10).join(out)}
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""
(HERE / "index.html").write_text(html)
print("index.html:", total, "s;", {k: v for k, v in slots.items()})
